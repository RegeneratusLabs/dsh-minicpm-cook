#!/usr/bin/env node
/**
 * Render the human-readable model catalog from data/models.json.
 *
 * The point is that there is exactly one place where a fact about a model lives.
 * Editing the markdown by hand would create a second one, and the two would
 * disagree within a release cycle.
 *
 *   node scripts/render-catalog.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')

const catalog = JSON.parse(await readFile(join(root, 'data', 'models.json'), 'utf8'))

/** Group models by family, preserving catalog order. */
function byFamily(models) {
  const groups = new Map()
  for (const model of models) {
    if (!groups.has(model.family)) groups.set(model.family, [])
    groups.get(model.family).push(model)
  }
  return groups
}

const FAMILY_TITLES = {
  minicpm5: 'MiniCPM5 (text, 2026)',
  sala: 'MiniCPM-SALA (text, million-token context)',
  minicpm41: 'MiniCPM4.1 (text, trainable sparse attention)',
  minicpm4: 'MiniCPM4 / MiniCPM3 (text)',
  'minicpm-v': 'MiniCPM-V (vision-language)',
  'minicpm-o': 'MiniCPM-o (omni: vision + speech)',
  ocr: 'MiniCPM-OCR (document parsing)',
  bitcpm: 'BitCPM4 (ternary research)',
  legacy: 'Legacy',
}

const lines = []
lines.push('# MiniCPM model catalog')
lines.push('')
lines.push('<!-- Generated by scripts/render-catalog.mjs from data/models.json. Do not edit by hand. -->')
lines.push('')
lines.push(`Compiled ${catalog.generatedAt} from ${catalog.upstream.repo}@${catalog.upstream.revision}.`)
lines.push('')
lines.push('Every row below is a catalog entry, not a summary of one. If a value here')
lines.push('disagrees with data/models.json, the JSON is authoritative and this file is stale.')
lines.push('')

const verified = catalog.models.filter((model) => model.confidence === 'verified').length
lines.push(`**${catalog.models.length} models**, ${verified} verified against a primary source, ${catalog.models.length - verified} marked unverified.`)
lines.push('')

// Overview table.
lines.push('## At a glance')
lines.push('')
lines.push('| Model | Params | Modality | Context | Licence | Released | Best for |')
lines.push('| --- | --- | --- | --- | --- | --- | --- |')
for (const model of catalog.models) {
  const params = model.activeParamsB !== undefined && model.activeParamsB !== model.paramsB
    ? `${model.paramsB}B (${model.activeParamsB}B active)`
    : `${model.paramsB}B`
  const licence = `${model.license}${model.licenseVerified ? '' : ' ⚠'}`
  lines.push(`| [${model.displayName}](https://huggingface.co/${model.hfId}) | ${params} | ${model.modality} | ${model.contextTokens.toLocaleString('en-US')} | ${licence} | ${model.releaseDate} | ${model.bestFor} |`)
}
lines.push('')
lines.push('⚠ = licence not verified against the model\'s own LICENSE file.')
lines.push('')

// Per-family detail.
for (const [family, models] of byFamily(catalog.models)) {
  lines.push(`## ${FAMILY_TITLES[family] ?? family}`)
  lines.push('')
  for (const model of models) {
    lines.push(`### ${model.displayName}`)
    lines.push('')
    lines.push(`- **Hugging Face:** \`${model.hfId}\`${model.msId ? ` · **ModelScope:** \`${model.msId}\`` : ''}`)
    lines.push(`- **Architecture:** ${model.architecture}${model.trustRemoteCode ? ' (needs `trust_remote_code=True`)' : ' (standard architecture, no remote code)'}`)
    lines.push(`- **Context:** ${model.contextTokens.toLocaleString('en-US')} tokens${model.extendedContextTokens ? ` (${model.extendedContextTokens.toLocaleString('en-US')} with RoPE scaling)` : ''}`)
    lines.push(`- **Licence:** ${model.license}${model.licenseVerified ? ' (verified)' : ' (NOT verified)'}`)
    if (model.chatTemplate?.name) lines.push(`- **Chat template:** \`${model.chatTemplate.name}\``)
    if (model.vision?.downsampleModes?.length) {
      lines.push(`- **Visual token budget:** ${model.vision.downsampleModes.join(' / ')} (default ${model.vision.defaultDownsample})`)
    }
    if (model.publishedHardware) {
      lines.push(`- **Official hardware floor:** ${model.publishedHardware.lora ?? model.publishedHardware.full}`)
    }
    const supported = Object.entries(model.frameworks ?? {})
      .filter(([, entry]) => entry?.supported === true)
      .map(([name]) => name)
    if (supported.length > 0) lines.push(`- **Backends:** ${supported.join(', ')}`)
    if (model.variants?.length > 0) {
      lines.push(`- **Published variants:** ${model.variants.map((variant) => `${variant.kind} (\`${variant.hfId}\`)`).join(', ')}`)
    }
    lines.push(`- **Confidence:** ${model.confidence}${model.confidenceNote ? ` — ${model.confidenceNote}` : ''}`)
    lines.push('')
    lines.push('Sources:')
    for (const source of model.sources) lines.push(`- ${source}`)
    lines.push('')
  }
}

lines.push('## Licence rules recorded')
lines.push('')
for (const [name, rules] of Object.entries(catalog.licenses)) {
  lines.push(`### ${name}`)
  lines.push('')
  lines.push(`- Redistributable: **${rules.redistributable}**`)
  lines.push(`- Commercial use: **${rules.commercialUse}**`)
  lines.push(`- Attribution required: **${rules.attributionRequired}**`)
  lines.push(`- ${rules.notes}`)
  if (rules.sourceUrl) lines.push(`- Source: ${rules.sourceUrl}`)
  lines.push('')
}

await writeFile(join(root, 'docs', 'models.md'), `${lines.join('\n')}\n`)
console.log(`wrote docs/models.md (${catalog.models.length} models)`)
